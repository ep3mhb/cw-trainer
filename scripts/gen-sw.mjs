/**
 * Generate the service worker after a build.
 *
 * Phase 1 must complete a whole training session with the network disabled
 * (acceptance criterion 7), so every built asset is precached by name. The
 * list is generated from dist/ rather than maintained by hand, because a
 * missed entry is an offline failure nobody notices until they try it on a
 * train.
 *
 * No Workbox, no build plugin: the whole offline story is the few dozen
 * lines below, which a volunteer can read.
 */

import { readdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

// fileURLToPath, not URL.pathname: the checkout path may contain spaces,
// which pathname percent-encodes.
const DIST = fileURLToPath(new URL('../dist/', import.meta.url));

async function walk(dir) {
  const found = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) found.push(...(await walk(full)));
    else found.push(full);
  }
  return found;
}

const files = (await walk(DIST))
  .map((f) => `./${relative(DIST, f).split(/[\\/]/).join('/')}`)
  // Sourcemaps are debugging aids, not part of the offline app; precaching
  // them would quadruple the install size for no benefit offline.
  .filter((f) => f !== './sw.js' && !f.endsWith('.map'))
  // The user manual (two PDFs, some 8 MB together) is read online and cached
  // on first open by the fetch handler below; precaching it would make every
  // install download it whether or not the member ever opens it.
  .filter((f) => !f.startsWith('./manual/'))
  /*
   * Dotfiles are never ours. macOS writes .DS_Store into public/ the moment
   * anyone opens that folder in Finder, Vite copies the whole of public/ into
   * dist/, and this list is generated from dist/ — so one Finder visit was
   * enough to put "./.DS_Store" into the precache. That is not cosmetic:
   * cache.addAll() is atomic, so if the file is not on the server (it is
   * excluded from the release zip, as it should be) the install rejects, the
   * service worker never activates, and offline operation — acceptance
   * criterion 7 — stops working for everyone. Caught in the 0.8.9 build.
   */
  .filter((f) => !f.split('/').some((part) => part.startsWith('.') && part !== '.'))
  .sort();

// Version the cache by the content of everything in it, so a deploy always
// replaces a stale cache and never serves half of each.
const hash = createHash('sha256');
for (const file of files) hash.update(await readFile(join(DIST, file.slice(2))));
const version = hash.digest('hex').slice(0, 12);

const sw = `/* Generated by scripts/gen-sw.mjs — do not edit. Build ${version}. */
const CACHE = 'cw-trainer-${version}';
const ASSETS = ${JSON.stringify(files, null, 2)};

/*
 * Install, then WAIT. No skipWaiting here on purpose: taking over the moment
 * a new build lands would serve new files to a page still running the old
 * JavaScript, and the member never asked for that. The page shows a banner
 * and posts 'skip-waiting' when they press Reload \u2014 see the message
 * handler below.
 */
self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(ASSETS)));
});

self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'skip-waiting') void self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

/*
 * Network first for the page, cache first for everything else.
 *
 * The hashed files under assets/ are immutable — a new build renames them —
 * so the cache is the right answer for those and costs no request. index.html
 * is the opposite: it NAMES those hashes, and a stale copy names files that
 * may no longer exist.
 *
 * That is not hypothetical. An iPhone was found serving a cached index.html
 * whose script had gone from both the cache and the server: the shell
 * rendered, the script 404'd, nothing booted. And it could never recover on
 * its own, because every escape route — the update banner, the 'skip-waiting'
 * message, the periodic check — lives in the JavaScript that was not running.
 * A private window worked, which is what gave it away.
 *
 * So the page itself is fetched from the network when there is one, and falls
 * back to the cache only when offline. One small request per visit buys a
 * guarantee that a member can never be pinned to a dead build.
 */
self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return;

  const url = new URL(request.url);
  const isPage = request.mode === 'navigate'
    || url.pathname.endsWith('/index.html')
    || url.pathname === '/' || url.pathname.endsWith('/');

  if (isPage) {
    event.respondWith(
      // cache: 'no-store' — go past the browser's OWN http cache, not just
      // ours. The shell is served with no Cache-Control header at all, which
      // leaves a browser free to cache it heuristically for as long as it
      // likes; an iPhone did exactly that and held a shell naming a script
      // that had since been deleted. Asking the network has to mean asking
      // the network.
      fetch(request, { cache: 'no-store' })
        .then((response) => {
          if (response.ok && response.type === 'basic') {
            const copy = response.clone();
            void caches.open(CACHE).then((cache) => cache.put('./index.html', copy));
          }
          return response;
        })
        // Offline: the shell from the cache, for any route.
        .catch(() => caches.match('./index.html').then((hit) => hit ?? Response.error())),
    );
    return;
  }

  event.respondWith(
    caches.match(request, { ignoreSearch: true }).then((hit) => {
      if (hit !== undefined) return hit;
      return fetch(request)
        .then((response) => {
          if (response.ok && response.type === 'basic') {
            const copy = response.clone();
            void caches.open(CACHE).then((cache) => cache.put(request, copy));
          }
          return response;
        })
        .catch(() => Response.error());
    }),
  );
});
`;

/*
 * Parse what we are about to ship. A service worker with a syntax error does
 * not announce itself: the browser silently refuses to install it, the page
 * is never controlled, and offline use and update detection both disappear
 * with no error anywhere a member or a test would look. Caught exactly that
 * way once, by `node --check` on the output rather than by any test.
 */
try {
  new (Function.constructor)(sw);
} catch (error) {
  console.error('gen-sw: the generated worker does not parse \u2014 refusing to write it.');
  console.error(String(error));
  process.exit(1);
}

await writeFile(join(DIST, 'sw.js'), sw, 'utf8');
console.log(`gen-sw: precaching ${files.length} files, cache cw-trainer-${version}`);
